# 의도: 파이썬 리스트 기본 생성 및 조작 예시 코드 작성
my_list = [1, 2, 3, 4, 5]
print("기본 리스트:", my_list)

my_list.append(6)
print("항목 추가 후:", my_list)

my_list.remove(3)
print("항목 제거 후:", my_list)

print("리스트 길이:", len(my_list))
print("첫 번째 항목:", my_list[0])
print("마지막 항목:", my_list[-1])
print("슬라이싱 [1:3]:", my_list[1:3])
